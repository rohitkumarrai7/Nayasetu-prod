// Deterministic first-draft templates (L5 offline path). Used when no LLM is configured or the LLM
// fails. Grounded by construction: authorities are inserted verbatim from the VERIFIED list, and
// every fact the advocate hasn't supplied is a visible [TO CONFIRM] gap — nothing is invented.
export interface DraftInput {
  docType: string;
  issue: string;
  facts: string;
  clientName?: string;
  categoryLabel?: string;
  authorities: { caseName: string; citationString?: string; relevancePassage: string }[];
  today?: Date;
}

const TITLES: Record<string, string> = {
  legal_notice: "LEGAL NOTICE",
  demand_letter: "DEMAND LETTER",
  claim_petition: "CLAIM PETITION (DRAFT OUTLINE)",
  consumer_complaint: "CONSUMER COMPLAINT (DRAFT OUTLINE)",
  written_statement: "WRITTEN STATEMENT (DRAFT OUTLINE)",
  complaint: "COMPLAINT (DRAFT OUTLINE)",
  petition: "PETITION (DRAFT OUTLINE)",
  bail_application: "BAIL APPLICATION (DRAFT OUTLINE)",
};

function authorityLines(a: DraftInput["authorities"]): string[] {
  if (a.length === 0) return ["[TO CONFIRM — no authority was verified for this issue; add one after research]"];
  return a.map((x, i) => `${i + 1}. ${x.caseName}${x.citationString ? `, ${x.citationString}` : ""}.`);
}

export function buildDraft(d: DraftInput): string {
  const date = (d.today ?? new Date()).toISOString().slice(0, 10);
  const client = d.clientName || "[CLIENT NAME]";
  const title = TITLES[d.docType] ?? d.docType.replace(/_/g, " ").toUpperCase();
  const facts = d.facts.trim() || "[TO CONFIRM — set out the material facts with dates]";
  const isLetter = ["legal_notice", "demand_letter"].includes(d.docType);

  if (isLetter) {
    return [
      title,
      "",
      `Date: ${date}`,
      "By Registered Post A.D. / Speed Post / Email",
      "",
      "To,",
      "[NAME AND ADDRESS OF THE NOTICEE]",
      "",
      `Subject: ${d.issue.slice(0, 160)}`,
      "",
      `Under instructions from and on behalf of my client, ${client}, I hereby serve upon you the following notice:`,
      "",
      "1. FACTS",
      facts,
      "",
      "2. LEGAL POSITION",
      `My client's claim arises under the applicable law${d.categoryLabel ? ` governing ${d.categoryLabel.toLowerCase()} matters` : ""} [TO CONFIRM — statutory provisions]. My client relies, inter alia, on:`,
      ...authorityLines(d.authorities),
      "",
      "3. DEMAND",
      "You are hereby called upon to [TO CONFIRM — specific relief: pay ₹____ / refund / repair / vacate / settle the claim] within [15] days of receipt of this notice.",
      "",
      "4. CONSEQUENCES",
      "Failing compliance, my client shall be constrained to initiate appropriate civil and/or criminal proceedings against you before the competent forum, entirely at your risk as to costs and consequences.",
      "",
      "A copy of this notice has been retained in my office for record and further action.",
      "",
      "[ADVOCATE NAME]",
      "Advocate, Enrolment No. [____]",
      "[Address / Phone / Email]",
      "",
      "— First draft generated by NyayaSetu. Review every [TO CONFIRM] item before sending. —",
    ].join("\n");
  }

  return [
    title,
    "",
    "BEFORE THE [NAME OF COURT / TRIBUNAL / COMMISSION], [PLACE]",
    "",
    `In the matter of: ${client} ... Petitioner / Complainant`,
    "Versus",
    "[OPPOSITE PARTY] ... Respondent / Opposite Party",
    "",
    "1. JURISDICTION",
    "[TO CONFIRM — territorial, pecuniary and subject-matter jurisdiction of this forum]",
    "",
    "2. FACTS OF THE CASE",
    facts,
    "",
    "3. GROUNDS",
    `A. ${d.issue.slice(0, 200)}`,
    "B. [TO CONFIRM — further grounds]",
    "",
    "4. AUTHORITIES RELIED UPON (verified against the corpus)",
    ...authorityLines(d.authorities),
    "",
    "5. LIMITATION",
    "[TO CONFIRM — the proceeding is within the period of limitation]",
    "",
    "6. PRAYER",
    "It is therefore most respectfully prayed that this Hon'ble [Court/Tribunal/Commission] may be pleased to:",
    "(a) [TO CONFIRM — principal relief];",
    "(b) award costs; and",
    "(c) pass any other order deemed fit in the interest of justice.",
    "",
    `Place: [____]    Date: ${date}`,
    "",
    "Petitioner / Complainant                      Through Counsel",
    "",
    "VERIFICATION: [TO CONFIRM — verification clause and supporting affidavit as required by the forum]",
    "",
    "— First draft generated by NyayaSetu. Review every [TO CONFIRM] item before filing. —",
  ].join("\n");
}
